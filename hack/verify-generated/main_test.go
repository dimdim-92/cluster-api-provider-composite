var fixtureOutputs = []string{
	"api/config/crd/bases/example.yaml",
	"api/v1beta2/zz_generated.deepcopy.go",
	"config/rbac/role.yaml",
	"helm/crds/example.yaml",
	"helm/templates/_generated-rbac.tpl",
}

func TestGeneratedVerification_PositiveAndNegativeControls(t *testing.T) {
	for _, scenario := range []string{"valid", "missing", "stale", "extra-crd", "extra-generated-go", "extra-reserved-go"} {
		t.Run(scenario, func(t *testing.T) {
			root := t.TempDir()
			require.NoError(t, generateFixture(root))
			switch scenario {
			case "missing":
				require.NoError(t, os.Remove(filepath.Join(root, fixtureOutputs[1])))
			case "stale":
				require.NoError(t, os.WriteFile(filepath.Join(root, fixtureOutputs[0]), []byte("stale\n"), 0o600))
			case "extra-crd":
				writeFixture(t, root, "api/config/crd/bases/obsolete.yaml", "old\n")
			case "extra-generated-go":
				writeFixture(t, root, "internal/obsolete.go", "// Code generated by a test. DO NOT EDIT.\npackage internal\n")
			case "extra-reserved-go":
				writeFixture(t, root, "api/v1beta2/zz_generated.obsolete.go", "package v1beta2\n")
			}
			before, err := generatedInventory(root)
			require.NoError(t, err)
			err = verify(root, generateFixture)
			if scenario == "valid" {
				require.NoError(t, err)
			} else {
				require.ErrorIs(t, err, errStaleGenerated)
			}
			after, err := generatedInventory(root)
			require.NoError(t, err)
			assert.Equal(t, before, after, "verification must not repair the source")
		})
	}
}

func TestGeneratedVerification_ExcludesLocalState(t *testing.T) {
	root := t.TempDir()
	require.NoError(t, generateFixture(root))
	private := []string{
		".env",
		"mgmt.yaml",
		"local.kubeconfig",
		"tests/integration/kubeconfig",
		".tools/tool",
		".idea/workspace.xml",
		"helm/charts/private.tgz",
		"out/archive.tar",
		"api/vendor/external.go",
		"api/third_party/external.go",
		"api/.git/config",
	}
	for _, path := range private {
		writeFixture(t, root, path, "private fixture\n")
	}
	err := verify(root, func(scratch string) error {
		for _, path := range private {
			_, err := os.Stat(filepath.Join(scratch, path))
			require.True(t, os.IsNotExist(err), "must not copy %s", path)
		}
		return generateFixture(scratch)
	})
	require.NoError(t, err)
}

func TestGeneratedVerification_PropagatesGeneratorFailure(t *testing.T) {
	root := t.TempDir()
	require.NoError(t, generateFixture(root))
	require.ErrorIs(t, verify(root, func(string) error { return os.ErrPermission }), os.ErrPermission)
}

func generateFixture(root string) error {
	for _, path := range fixtureOutputs {
		if err := os.MkdirAll(filepath.Dir(filepath.Join(root, path)), 0o700); err != nil {
			return fmt.Errorf("creating fixture directory: %w", err)
		}
		data := "generated: fixture\n"
		if filepath.Ext(path) == ".go" {
			data = "// Code generated by a test. DO NOT EDIT.\npackage v1beta2\n"
		}
		if err := os.WriteFile(filepath.Join(root, path), []byte(data), 0o600); err != nil {
			return fmt.Errorf("writing fixture output: %w", err)
		}
	}
	return nil
}

func writeFixture(t *testing.T, root, path, data string) {
	t.Helper()
	require.NoError(t, os.MkdirAll(filepath.Dir(filepath.Join(root, path)), 0o700))
	require.NoError(t, os.WriteFile(filepath.Join(root, path), []byte(data), 0o600))
}
