const fixtureHeader = "// Copyright 2026 Numspot.\n// Licensed under the Apache License, Version 2.0.\n"

func TestHeaders_CheckDoesNotFix(t *testing.T) {
	root := headerFixture(t)
	path := filepath.Join(root, "example.go")
	original := []byte("// Copyright 2026 Numspot.\n// SPDX-License-Identifier: Apache-2.0\n\npackage example\n")
	require.NoError(t, os.WriteFile(path, original, 0o640))
	require.Error(t, run(root, false))
	after, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Equal(t, original, after)
	require.NoError(t, run(root, true))
	require.NoError(t, run(root, false))
	fixed, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Equal(t, fixtureHeader+"\npackage example\n", string(fixed))
	info, err := os.Stat(path)
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0o640), info.Mode().Perm())
	require.NoError(t, run(root, true))
	after, err = os.ReadFile(path)
	require.NoError(t, err)
	assert.Equal(t, fixed, after)
}

func TestHeaders_ChecksAnExplicitRootSymlink(t *testing.T) {
	root := headerFixture(t)
	path := filepath.Join(root, "example.go")
	require.NoError(t, os.WriteFile(path, []byte("package example\n"), 0o600))
	alias := filepath.Join(t.TempDir(), "repository")
	if err := os.Symlink(root, alias); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	require.Error(t, run(alias, false))
	require.NoError(t, run(alias, true))
	require.NoError(t, run(root, false))
}

func TestHeaders_PreserveBuildConstraints(t *testing.T) {
	root := headerFixture(t)
	path := filepath.Join(root, "example.go")
	prefix := "//go:build linux\n// +build linux\n\n"
	require.NoError(t, os.WriteFile(path, []byte(prefix+"package example\n"), 0o600))
	require.NoError(t, run(root, true))
	data, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Equal(t, prefix+fixtureHeader+"\npackage example\n", string(data))
}

func TestHeaders_GeneratedFilesAreCheckedNotRewritten(t *testing.T) {
	root := headerFixture(t)
	path := filepath.Join(root, "zz_generated.deepcopy.go")
	original := []byte("//go:build !ignore_autogenerated\n\n// Code generated by a test. DO NOT EDIT.\n\npackage example\n")
	require.NoError(t, os.WriteFile(path, original, 0o600))
	require.Error(t, run(root, false))
	require.Error(t, run(root, true))
	after, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Equal(t, original, after)
	require.NoError(
		t,
		os.WriteFile(
			path,
			[]byte("//go:build !ignore_autogenerated\n\n"+fixtureHeader+"\n// Code generated by a test. DO NOT EDIT.\n\npackage example\n"),
			0o600,
		),
	)
	require.NoError(t, run(root, false))
}

func TestHeaders_DoNotReplaceForeignAttribution(t *testing.T) {
	for _, preamble := range []string{
		"// Copyright 2020 Another Project.\n",
		legacyHeader + "\n// Copyright 2020 Another Project.\n",
		"// SPDX-License-Identifier: BSD-3-Clause\n",
	} {
		root := headerFixture(t)
		path := filepath.Join(root, "example.go")
		original := []byte(preamble + "\npackage example\n")
		require.NoError(t, os.WriteFile(path, original, 0o600))
		require.Error(t, run(root, true))
		after, err := os.ReadFile(path)
		require.NoError(t, err)
		assert.Equal(t, original, after)
	}
}

func TestHeaders_DoNotRewriteReservedGeneratedNames(t *testing.T) {
	for _, prefix := range []string{"", legacyHeader} {
		root := headerFixture(t)
		path := filepath.Join(root, "zz_generated.other.go")
		original := []byte(prefix + "\npackage example\n")
		require.NoError(t, os.WriteFile(path, original, 0o600))
		require.Error(t, run(root, true))
		after, err := os.ReadFile(path)
		require.NoError(t, err)
		assert.Equal(t, original, after)
	}
}

func TestHeaders_ExcludeExternalAndLocalState(t *testing.T) {
	root := headerFixture(t)
	for _, directory := range []string{"vendor", "third_party", ".git", ".tools", "out", "bin", "tests/crds", "api/vendor", "api/third_party", "api/.git"} {
		path := filepath.Join(root, directory)
		require.NoError(t, os.MkdirAll(path, 0o700))
		require.NoError(t, os.WriteFile(filepath.Join(path, "external.go"), []byte("package external\n"), 0o600))
	}
	require.NoError(t, os.WriteFile(filepath.Join(root, "README.md"), []byte("# Documentation\n"), 0o600))
	require.NoError(t, run(root, false))
	require.NoError(t, run(root, true))
}

func headerFixture(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	require.NoError(t, os.Mkdir(filepath.Join(root, "hack"), 0o700))
	require.NoError(t, os.WriteFile(filepath.Join(root, "hack", "boilerplate.go.txt"), []byte(fixtureHeader), 0o600))
	return root
}
