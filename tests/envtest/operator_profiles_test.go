func testOperatorProfiles(t *testing.T, installation *envtest.Environment, c client.Client, binary string) {
	ns := operatorNamespace(t, c, "profiles")
	outside := operatorNamespace(t, c, "profile-outside")
	credentials := operatorCredentials(t, installation, c, ns)
	p := regionalProfileDefinition()
	p.Name, p.GenerateName = "profile-"+ns, ""
	spec := infrav1.CompositeClusterSpec{
		ControlPlaneEndpoint: infrav1.APIEndpoint{Host: "192.0.2.50", Port: 6443},
	}
	_, active := runtimeClusterWithSpec(t, c, ns, "active-profile", "profiles", spec)
	_, otherNamespace := runtimeClusterWithSpec(t, c, outside, "outside-profile", "profiles", spec)
	_, otherFilter := runtimeClusterWithSpec(t, c, ns, "filtered-profile", "another", spec)
	provider := runtimeProvider(t, c, active, p.Name, "regional")
	runtimeProvider(t, c, otherNamespace, p.Name, "regional")
	runtimeProvider(t, c, otherFilter, p.Name, "regional")
	startOperator(t, binary, credentials, ns, "--watch-filter=profiles")
	require.Eventually(t, func() bool {
		current := &infrav1.CompositeProvider{}
		if c.Get(t.Context(), client.ObjectKeyFromObject(provider), current) != nil {
			return false
		}
		ready := condition(current.Status.Conditions, infrav1.ReadyCondition)
		return ready != nil && ready.Reason == infrav1.ProfileUnavailableReason
	}, 10*time.Second, 100*time.Millisecond)
	// Creation/finalizer events must wake the indexed consumer before its 30s poll.
	createRegionalProfile(t, c, p)
	waitRuntimeObject(t, c, fakeClusterGVK, ns, active.Name)
	waitRuntimeObject(t, c, kubeadmConfigTemplateGVK, ns, active.Name+"-"+provider.Name)
	require.Eventually(t, func() bool {
		current := &infrav1.CompositeProvider{}
		return c.Get(t.Context(), client.ObjectKeyFromObject(provider), current) == nil && current.Status.InfrastructureRef.Name == active.Name
	}, 10*time.Second, 100*time.Millisecond)
	for _, excluded := range []*infrav1.CompositeCluster{otherNamespace, otherFilter} {
		current := &infrav1.CompositeCluster{}
		require.NoError(t, c.Get(t.Context(), client.ObjectKeyFromObject(excluded), current))
		assert.Equal(t, excluded.ResourceVersion, current.ResourceVersion)
		assertRuntimeAbsent(t, c, fakeClusterGVK, excluded.Namespace, excluded.Name)
	}
	testRuntimeTemplateProfileHold(t, c, outside)
}

func testRuntimeTemplateProfileHold(t *testing.T, c client.Client, namespace string) {
	t.Helper()
	p := regionalProfileDefinition()
	p.Name, p.GenerateName = "template-profile-"+namespace, ""
	_, cc := runtimeClusterWithSpec(t, c, namespace, "reference-outside-watch", "profiles", infrav1.CompositeClusterSpec{})
	template := runtimeProvider(t, c, cc, p.Name, "regional")
	createRegionalProfile(t, c, p)
	key := client.ObjectKeyFromObject(p)
	require.Eventually(t, func() bool {
		return c.Get(t.Context(), key, p) == nil && len(p.Finalizers) > 0 && p.Status.ObservedGeneration == p.Generation
	}, 10*time.Second, 100*time.Millisecond)
	require.Contains(t, p.Finalizers, infrav1.ProviderInUseFinalizer)
	require.NoError(t, c.Delete(t.Context(), p))
	require.Eventually(t, func() bool {
		return c.Get(t.Context(), key, p) == nil && !p.DeletionTimestamp.IsZero()
	}, 10*time.Second, 100*time.Millisecond)
	require.Never(t, func() bool {
		return apierrors.IsNotFound(c.Get(t.Context(), key, &infrav1.CompositeProviderTemplate{}))
	}, time.Second, 50*time.Millisecond, "a provider outside the watch namespace must retain its profile")
	require.NoError(t, c.Delete(t.Context(), template))
	// A profile metadata event triggers an immediate global recheck; periodic
	// requeues provide convergence when no event is generated by an outside consumer.
	err := c.Patch(t.Context(), p, client.RawPatch(types.MergePatchType, []byte(`{"metadata":{"labels":{"test.example.org/recheck":"true"}}}`)))
	require.NoError(t, client.IgnoreNotFound(err))
	require.Eventually(t, func() bool {
		return apierrors.IsNotFound(c.Get(t.Context(), key, &infrav1.CompositeProviderTemplate{}))
	}, 10*time.Second, 100*time.Millisecond)
}

func runtimeProvider(t *testing.T, c client.Client, cc *infrav1.CompositeCluster, templateName, name string) *infrav1.CompositeProvider {
	t.Helper()
	p := &infrav1.CompositeProvider{
		ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: cc.Namespace},
		Spec: infrav1.CompositeProviderSpec{
			ClusterRef:  infrav1.CompositeClusterReference{Name: cc.Name},
			TemplateRef: infrav1.CompositeProviderReference{Name: templateName},
		},
	}
	// Names must be unique when several scoped clusters share a namespace.
	p.Name = cc.Name + "-" + name
	require.NoError(t, c.Create(t.Context(), p))
	return p
}
